const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("pdfUtils", {
  version: () => ipcRenderer.invoke("app:version"),
  serverUrl: () => ipcRenderer.invoke("app:server-url"),
  loadConfig: () => ipcRenderer.invoke("config:load"),
  saveConfig: (config) => ipcRenderer.invoke("config:save", config),
  loginOnr: (payload) => ipcRenderer.invoke("onr:login", payload),
  pathForFile: (file) => webUtils.getPathForFile(file),
  openFile: (options) => ipcRenderer.invoke("dialog:open-file", options),
  openFiles: (options) => ipcRenderer.invoke("dialog:open-files", options),
  openDirectory: (options) => ipcRenderer.invoke("dialog:open-directory", options),
  savePdf: (options) => ipcRenderer.invoke("dialog:save-pdf", options),
  openPath: (target) => ipcRenderer.invoke("shell:open-path", target),
  showItemInFolder: (target) => ipcRenderer.invoke("shell:show-item-in-folder", target),
  openExternal: (target) => ipcRenderer.invoke("shell:open-external", target),
  ghostscriptStatus: () => ipcRenderer.invoke("dependencies:ghostscript-status"),
  installGhostscript: (payload) => ipcRenderer.invoke("dependencies:install-ghostscript", payload),
  writeLog: (payload) => ipcRenderer.invoke("logs:write", payload),
  listCertificates: () => ipcRenderer.invoke("certificates:list"),
  webPkiDiagnostics: () => ipcRenderer.invoke("webpki:diagnostics"),
  readCertificate: (payload) => ipcRenderer.invoke("webpki:read-certificate", payload),
  signHash: (payload) => ipcRenderer.invoke("webpki:sign-hash", payload),
  signData: (payload) => ipcRenderer.invoke("webpki:sign-data", payload),
  signPdfWithNative: (payload) => ipcRenderer.invoke("webpki:sign-pdf", payload),

  convertToPdfA: (payload) => ipcRenderer.invoke("pdfa:convert", payload),
  mergeFilesToPdf: (payload) => ipcRenderer.invoke("pdf:merge", payload),
  validatePdfA: (payload) => ipcRenderer.invoke("pdfa:validate", payload),
  validateSignatures: (payload) => ipcRenderer.invoke("signature:validate", payload),
  prepareSignaturePdf: (payload) => ipcRenderer.invoke("signature:prepare-pdf", payload),
  signPdfSession: (payload) => ipcRenderer.invoke("signature:sign-session", payload),
  saveSignedPdf: (payload) => ipcRenderer.invoke("signature:save-signed", payload),
  saveSignedPdfAuto: (payload) => ipcRenderer.invoke("signature:save-signed-auto", payload),
  cleanupSignature: (jobId) => ipcRenderer.invoke("signature:cleanup", jobId),

  onrStart: (payload) => ipcRenderer.invoke("onr:start", payload),
  onrComplete: (payload) => ipcRenderer.invoke("onr:complete", payload),
  onrSignatureSession: (payload) => ipcRenderer.invoke("onr:signature-session", payload),
  cancelOnrSignature: (operationId) => ipcRenderer.invoke("onr:cancel-signature", operationId),
  cancelWorkflow: (operationId) => ipcRenderer.invoke("workflow:cancel", operationId),

  checkUpdates: () => ipcRenderer.invoke("update:check"),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  onUpdateStatus: (callback) => ipcRenderer.on("update:status", (_event, state) => callback(state)),
  onDependencyProgress: (callback) => ipcRenderer.on("dependencies:progress", (_event, message) => callback(message)),
  onPdfAProgress: (callback) => ipcRenderer.on("pdfa:progress", (_event, message) => callback(message)),
  onMergeProgress: (callback) => ipcRenderer.on("pdf:merge-progress", (_event, message) => callback(message)),
  onSignatureProgress: (callback) => ipcRenderer.on("signature:progress", (_event, message) => callback(message)),
  onOnrProgress: (callback) => ipcRenderer.on("onr:progress", (_event, message) => callback(message)),

  loadOnrHistory: () => ipcRenderer.invoke("onr-history:load"),
  saveOnrHistory: (items) => ipcRenderer.invoke("onr-history:save", items),
  addOnrHistoryItem: (item) => ipcRenderer.invoke("onr-history:add", item)
});
